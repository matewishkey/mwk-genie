# --- put the genie in the box ------------------------------------------------
# Three letters to start Claude, from anywhere.
#
# The flag is the whole point of the shortcut. Without it you are asked to
# approve every single command, and setting a machine up is hundreds of them —
# you stop reading and start pressing enter, which is worse than not being asked
# at all. With it, you agree to the work in conversation and it gets on with it.
#
# That is a real trade, and it is why this does not belong on a work computer.
#
# It deliberately does not move you anywhere. Which folder you are in matters,
# and `cd` is the one command worth learning on day one.
alias ccc='claude --dangerously-skip-permissions'
